/**
 * Generates the typed API clients from the committed backend contracts (decision T12):
 *
 *   ../contracts/openapi/openapi.json     -> src/shared/api/generated/      (orval, mutator: shared/api/apiRequest.ts)
 *   ../contracts/graphql/schema.graphqls  -> src/shared/graphql/generated/  (graphql-codegen client-preset)
 *
 *   pnpm codegen          regenerate in place
 *   pnpm codegen:check    regenerate into a temp dir and fail (with a diff) when the committed output differs
 *
 * The contracts themselves come from the backend: ./gradlew :trellis-app:exportApiContracts.
 */
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { generate as generateGraphql } from "@graphql-codegen/cli";
import { generate as generateOpenApi } from "orval";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CONTRACTS = path.resolve(WEB, "../contracts");
const OPENAPI = path.join(CONTRACTS, "openapi/openapi.json");
const GRAPHQL_SCHEMA = path.join(CONTRACTS, "graphql/schema.graphqls");
const API_OUT = "src/shared/api/generated";
const GRAPHQL_OUT = "src/shared/graphql/generated";
const HEADER = "GENERATED by web/scripts/codegen.mjs from contracts/. DO NOT EDIT; run pnpm codegen.";

/** Generates both clients under `root` (the web dir, or a temp copy of it for --check). */
async function generateAll(root) {
  for (const dir of [API_OUT, GRAPHQL_OUT]) rmSync(path.join(root, dir), { recursive: true, force: true });

  await generateOpenApi({
    input: { target: OPENAPI },
    output: {
      target: path.join(root, API_OUT, "trellis-api.ts"),
      schemas: path.join(root, API_OUT, "model"),
      client: "axios-functions",
      mode: "tags",
      headers: true,
      indexFiles: false,
      override: {
        header: () => [HEADER],
        mutator: { path: path.join(root, "src/shared/api/apiRequest.ts"), name: "apiRequest" },
      },
    },
  });

  await generateGraphql(
    {
      silent: true,
      schema: GRAPHQL_SCHEMA,
      documents: [path.join(root, "src/**/*.{ts,tsx}"), `!${path.join(root, GRAPHQL_OUT)}/**`],
      ignoreNoDocuments: true,
      generates: {
        [`${path.join(root, GRAPHQL_OUT)}/`]: {
          preset: "client",
          presetConfig: { fragmentMasking: false },
          config: {
            // Documents are plain strings: no graphql-js runtime in the browser bundle.
            documentMode: "string",
            enumsAsTypes: true,
            useTypeImports: true,
            scalars: { DateTime: "string" },
            strictScalars: true,
          },
        },
      },
    },
    true,
  );
  // client-preset has no header option of its own.
  const graphqlDir = path.join(root, GRAPHQL_OUT);
  for (const file of readdirSync(graphqlDir)) {
    const target = path.join(graphqlDir, file);
    writeFileSync(target, `/* ${HEADER} */\n${readFileSync(target, "utf8")}`);
  }
}

async function check() {
  const scratch = mkdtempSync(path.join(tmpdir(), "trellis-codegen-"));
  try {
    // Documents and the mutator live in src/, so generate against a copy of it.
    cpSync(path.join(WEB, "src"), path.join(scratch, "src"), { recursive: true });
    await generateAll(scratch);
    let drift = false;
    for (const dir of [API_OUT, GRAPHQL_OUT]) {
      const committed = path.join(WEB, dir);
      const fresh = path.join(scratch, dir);
      try {
        execFileSync("diff", ["-ru", existsSync(committed) ? committed : "/dev/null", fresh], {
          stdio: "inherit",
        });
      } catch {
        drift = true;
      }
    }
    if (drift) {
      console.error("\nGenerated API clients are stale: run `pnpm codegen` and commit the result.");
      process.exit(1);
    }
    console.log("Generated API clients are up to date.");
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

if (process.argv.includes("--check")) {
  await check();
} else {
  await generateAll(WEB);
  console.log(`Generated ${API_OUT} and ${GRAPHQL_OUT}.`);
}
