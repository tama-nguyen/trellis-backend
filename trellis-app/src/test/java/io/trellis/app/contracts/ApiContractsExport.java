package io.trellis.app.contracts;

import static org.junit.jupiter.api.Assertions.assertEquals;

import graphql.schema.idl.SchemaPrinter;
import io.trellis.app.PostgresTestcontainer;
import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.server.LocalServerPort;
import org.springframework.context.annotation.Import;
import org.springframework.graphql.execution.GraphQlSource;
import org.springframework.test.context.ActiveProfiles;
import tools.jackson.core.util.DefaultIndenter;
import tools.jackson.core.util.DefaultPrettyPrinter;
import tools.jackson.core.util.Separators;
import tools.jackson.databind.json.JsonMapper;

/**
 * Tooling, not a test: boots the application (test profile, real Postgres) and writes or checks the
 * published API contracts, {@code contracts/openapi/openapi.json} (from springdoc) and {@code
 * contracts/graphql/schema.graphqls} (the merged schema of every module). Excluded from {@code
 * test}; run by {@code :trellis-app:exportApiContracts} (mode {@code write}) and {@code
 * :trellis-app:checkApiContracts} (mode {@code check}, part of {@code check}). The published npm
 * and PyPI contract packages are generated from these files (docs/architecture/contracts.md).
 */
@Tag(ApiContractsExport.TAG)
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@ActiveProfiles("test")
@Import(PostgresTestcontainer.class)
class ApiContractsExport {
  static final String TAG = "api-contracts";
  static final String MODE_PROPERTY = "trellis.api-contracts.mode";
  static final String MODE_WRITE = "write";
  static final String STALE_DIR_PROPERTY = "trellis.api-contracts.stale-dir";
  private static final String OPENAPI_FILE = "openapi/openapi.json";
  private static final String GRAPHQL_FILE = "graphql/schema.graphqls";
  private static final String API_DOCS = "/v3/api-docs";
  private static final String GENERATED_KEY = "x-generated";
  private static final String GENERATED_NOTE =
      "GENERATED by ./gradlew :trellis-app:exportApiContracts from the"
          + " backend code. DO NOT EDIT.";
  private static final String GRAPHQL_HEADER =
      "# GENERATED by ./gradlew :trellis-app:exportApiContracts from"
          + " */src/main/resources/graphql/**/*.graphqls. DO NOT EDIT.\n\n";

  @LocalServerPort private int port;

  @Autowired private GraphQlSource graphQlSource;

  private final JsonMapper json = JsonMapper.builder().build();

  @Test
  void exportOrCheck() throws Exception {
    Path contracts = Path.of(System.getProperty("trellis.contracts.dir"));
    Map<Path, String> fresh =
        Map.of(
            contracts.resolve(OPENAPI_FILE), openApi(),
            contracts.resolve(GRAPHQL_FILE), graphQlSchema());
    if (MODE_WRITE.equals(System.getProperty(MODE_PROPERTY))) {
      for (var entry : fresh.entrySet()) {
        Files.createDirectories(entry.getKey().getParent());
        Files.writeString(entry.getKey(), entry.getValue(), StandardCharsets.UTF_8);
      }
      return;
    }
    List<String> stale = new ArrayList<>();
    Path staleDir = Path.of(System.getProperty(STALE_DIR_PROPERTY, "build/api-contracts"));
    for (var entry : fresh.entrySet()) {
      String committed = Files.exists(entry.getKey()) ? Files.readString(entry.getKey()) : "";
      if (!committed.equals(entry.getValue())) {
        Path copy = staleDir.resolve(contracts.relativize(entry.getKey()));
        Files.createDirectories(copy.getParent());
        Files.writeString(copy, entry.getValue(), StandardCharsets.UTF_8);
        stale.add(
            contracts.relativize(entry.getKey()) + " (fresh copy: " + copy.toAbsolutePath() + ")");
      }
    }
    assertEquals(
        List.of(),
        stale,
        "API contracts are stale: run ./gradlew :trellis-app:exportApiContracts and commit contracts/");
  }

  private String openApi() throws IOException, InterruptedException {
    HttpResponse<String> response =
        HttpClient.newHttpClient()
            .send(
                HttpRequest.newBuilder(URI.create("http://localhost:" + port + API_DOCS)).build(),
                HttpResponse.BodyHandlers.ofString());
    assertEquals(200, response.statusCode(), response.body());
    Object document = sorted(json.readValue(response.body(), Object.class));
    if (document instanceof Map<?, ?> root && root.get("info") instanceof Map<?, ?> info) {
      @SuppressWarnings("unchecked") // built by sorted(): String keys only
      Map<String, Object> mutableInfo = (Map<String, Object>) info;
      mutableInfo.put(GENERATED_KEY, GENERATED_NOTE);
    }
    // Two-space indent and `"key": value`, the formatting Prettier and most editors produce.
    DefaultPrettyPrinter printer =
        new DefaultPrettyPrinter(
                Separators.createDefaultInstance()
                    .withObjectNameValueSpacing(Separators.Spacing.AFTER))
            .withObjectIndenter(new DefaultIndenter("  ", "\n"))
            .withArrayIndenter(new DefaultIndenter("  ", "\n"));
    return json.writer().with(printer).writeValueAsString(document) + "\n";
  }

  private String graphQlSchema() {
    SchemaPrinter printer =
        new SchemaPrinter(
            SchemaPrinter.Options.defaultOptions()
                .includeDirectives(false)
                .includeIntrospectionTypes(false)
                .includeScalarTypes(true)
                .includeSchemaDefinition(false));
    return GRAPHQL_HEADER + printer.print(graphQlSource.schema()).strip() + "\n";
  }

  /**
   * Key order of maps fixed (springdoc's order of paths and properties is not stable across runs).
   */
  private static Object sorted(Object node) {
    if (node instanceof Map<?, ?> map) {
      Map<String, Object> result = new TreeMap<>();
      map.forEach((k, v) -> result.put(String.valueOf(k), sorted(v)));
      return result;
    }
    if (node instanceof List<?> list) {
      return list.stream().map(ApiContractsExport::sorted).toList();
    }
    return node;
  }
}
