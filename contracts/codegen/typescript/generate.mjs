/**
 * Generates the TypeScript half of the published contracts (decision T22) into
 * contracts/packages/npm/:
 *
 *   contracts/openapi/openapi.json    -> src/openapi.ts        (openapi-typescript: paths, components)
 *   contracts/graphql/schema.graphqls -> src/graphql.ts        (graphql-codegen: one type per schema type)
 *   contracts/graphql/schema.graphqls -> schema.graphqls       (shipped as-is, for consumer codegen)
 *
 *   scripts/contracts/generate.sh            regenerate in place
 *   scripts/contracts/generate.sh --check    fail with a diff when the committed output is stale
 *
 * Generated files are committed so a reviewer sees what a contract change does to consumers, and so
 * the publish job only has to compile. Hand-written files (src/index.ts, src/client.ts) are never
 * touched here. Generator versions are pinned in contracts/packages/npm/package.json.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { generate as generateGraphql } from "@graphql-codegen/cli";
import openapiTS, { astToString } from "openapi-typescript";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const CONTRACTS = path.resolve(HERE, "../..");
const PACKAGE = path.join(CONTRACTS, "packages/npm");
const OPENAPI = path.join(CONTRACTS, "openapi/openapi.json");
const GRAPHQL_SCHEMA = path.join(CONTRACTS, "graphql/schema.graphqls");

// Relative to the package root; these three are the only files the generator owns.
const OUTPUTS = ["src/openapi.ts", "src/graphql.ts", "schema.graphqls"];

const header = (source) =>
  `/* GENERATED by contracts/codegen/typescript/generate.mjs from ${source}. DO NOT EDIT.\n` +
  ` * Change the backend, export the contracts, then run scripts/contracts/generate.sh. */\n`;

async function generateAll(root) {
  mkdirSync(path.join(root, "src"), { recursive: true });

  const openapi = astToString(await openapiTS(new URL(`file://${OPENAPI}`), { alphabetize: true }));
  writeFileSync(path.join(root, "src/openapi.ts"), header("contracts/openapi/openapi.json") + openapi);

  // graphql-codegen writes the file itself, so point it at the target and prepend the header after.
  const graphqlTarget = path.join(root, "src/graphql.ts");
  await generateGraphql(
    {
      silent: true,
      schema: GRAPHQL_SCHEMA,
      generates: {
        [graphqlTarget]: {
          plugins: ["typescript"],
          config: {
            enumsAsTypes: true,
            useTypeImports: true,
            // The backend serialises DateTime as an ISO-8601 string (trellis-platform-web scalar).
            scalars: { DateTime: "string" },
            strictScalars: true,
            skipTypename: true,
            avoidOptionals: false,
          },
        },
      },
    },
    true,
  );
  writeFileSync(
    graphqlTarget,
    header("contracts/graphql/schema.graphqls") + readFileSync(graphqlTarget, "utf8"),
  );

  // The schema travels with the package: a consumer generates its own operation types from it.
  writeFileSync(path.join(root, "schema.graphqls"), readFileSync(GRAPHQL_SCHEMA, "utf8"));
}

async function check() {
  const scratch = mkdtempSync(path.join(tmpdir(), "trellis-contracts-ts-"));
  try {
    await generateAll(scratch);
    let drift = false;
    for (const file of OUTPUTS) {
      try {
        execFileSync("diff", ["-u", path.join(PACKAGE, file), path.join(scratch, file)], {
          stdio: "inherit",
        });
      } catch {
        drift = true;
      }
    }
    if (drift) {
      console.error("\nGenerated TypeScript contracts are stale: run scripts/contracts/generate.sh.");
      process.exit(1);
    }
    console.log(`generated TypeScript contracts are up to date (${OUTPUTS.length} files)`);
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

if (process.argv.includes("--check")) {
  await check();
} else {
  await generateAll(PACKAGE);
  console.log(`generated ${OUTPUTS.map((f) => `contracts/packages/npm/${f}`).join(", ")}`);
}
