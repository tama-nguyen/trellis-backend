"""Generate pydantic v2 models from contracts/events/**/*.schema.json.

Output: contracts/packages/python/src/trellis_contracts/events/ (never edit by hand), the event half
of the published ``trellis-contracts`` package (decision T22, docs/architecture/contracts.md).

    scripts/contracts/generate.sh            # regenerate both halves
    scripts/contracts/generate.sh --check    # CI: fail if output would change

Uses datamodel-code-generator (pinned in scripts/contracts/generate.sh so output is reproducible),
then applies two deterministic post-processing steps:

* ``dict[str, Any]`` (an untyped JSON object, e.g. the envelope payload) becomes
  ``dict[str, JsonValue]`` (pydantic's own ``JsonValue``), because the package is typed and ships
  ``py.typed``.
* Payload modules get ``EVENT_TYPE``/``EVENT_VERSION`` constants, and ``index.py`` maps
  ``(eventType, eventVersion)`` to the payload model for the payload registry.

Models are tolerant readers (``extra="ignore"``): consumers accept additive fields without a
version bump, as the contracts' versioning rules allow.
"""

import argparse
import difflib
import filecmp
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

CONTRACTS = Path(__file__).resolve().parents[2]
EVENTS = CONTRACTS / "events"
OUTPUT = CONTRACTS / "packages" / "python" / "src" / "trellis_contracts" / "events"
ENVELOPE_SCHEMA = EVENTS / "envelope.schema.json"
PAYLOAD_SCHEMA = re.compile(r"^v(?P<version>[1-9][0-9]*)\.schema\.json$")
HEADER = (
    "# GENERATED by contracts/codegen/python/generate.py from {source}. DO NOT EDIT.\n"
    "# Change the JSON Schema, then run: scripts/contracts/generate.sh"
)
CODEGEN_ARGS = [
    "--input-file-type", "jsonschema",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.12",
    "--snake-case-field",
    "--allow-population-by-field-name",
    "--use-annotated",
    "--field-constraints",
    "--use-standard-collections",
    "--use-union-operator",
    "--extra-fields", "ignore",
    "--output-datetime-class", "AwareDatetime",
    "--disable-timestamp",
    "--use-title-as-name",
    "--use-double-quotes",
    "--capitalise-enum-members",
    "--set-default-enum-member",
    "--use-schema-description",
    "--no-use-field-description",
    "--no-formatters",  # formatting happens once, in generate(), with pinned settings
]  # fmt: skip


@dataclass(frozen=True)
class Payload:
    schema: Path
    event_type: str
    version: int
    module: str
    model: str


def _title(schema: Path) -> str:
    match = re.search(r'"title"\s*:\s*"([A-Za-z0-9]+)"', schema.read_text(encoding="utf-8"))
    if match is None:
        raise SystemExit(f"{schema}: a contract needs a PascalCase 'title' (the model name)")
    return match.group(1)


def _payloads() -> list[Payload]:
    found = []
    for schema in sorted(EVENTS.glob("*/v*.schema.json")):
        match = PAYLOAD_SCHEMA.match(schema.name)
        if match is None:
            continue
        event_type = schema.parent.name
        version = int(match.group("version"))
        module = f"{event_type.replace('.', '_')}_v{version}"
        found.append(Payload(schema, event_type, version, module, _title(schema)))
    return found


def _codegen(schema: Path, target: Path) -> None:
    source = schema.relative_to(CONTRACTS.parent).as_posix()
    subprocess.run(
        [
            sys.executable, "-m", "datamodel_code_generator",
            "--input", str(schema), "--output", str(target),
            "--custom-file-header", HEADER.format(source=source),
            *CODEGEN_ARGS,
        ],
        check=True,
    )  # fmt: skip
    text = target.read_text(encoding="utf-8")
    if "dict[str, Any]" in text:
        text = text.replace("dict[str, Any]", "dict[str, JsonValue]")
        text = re.sub(r"from typing import (.*)\bAny, ?", r"from typing import \1", text)
        text = re.sub(r"from typing import (.*), Any\n", r"from typing import \1\n", text)
        # pydantic ships its own recursive JsonValue alias, so the package needs no runtime of ours.
        text = text.replace("from pydantic import ", "from pydantic import JsonValue\nfrom pydantic import ", 1)
    target.write_text(text, encoding="utf-8")


def generate(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for stale in out.glob("*.py"):  # a deleted contract must not leave its module behind
        stale.unlink()
    (out / "__init__.py").write_text(
        f'{HEADER.format(source="contracts/events")}\n"""Models generated from the event contracts."""\n',
        encoding="utf-8",
    )
    _codegen(ENVELOPE_SCHEMA, out / "envelope.py")
    payloads = _payloads()
    for payload in payloads:
        target = out / f"{payload.module}.py"
        _codegen(payload.schema, target)
        with target.open("a", encoding="utf-8") as fh:
            fh.write(
                f'\n\nEVENT_TYPE: Final = "{payload.event_type}"\nEVENT_VERSION: Final = {payload.version}\n'
            )
        text = target.read_text(encoding="utf-8")
        target.write_text(text.replace("from typing import ", "from typing import Final, ", 1), encoding="utf-8")
    imports = "\n".join(f"from trellis_contracts.events import {p.module}" for p in payloads)
    entries = "\n".join(
        f"    ({p.module}.EVENT_TYPE, {p.module}.EVENT_VERSION): {p.module}.{p.model}," for p in payloads
    )
    (out / "index.py").write_text(
        f"{HEADER.format(source='contracts/events')}\n"
        '"""Every payload contract: (eventType, eventVersion) -> model."""\n\n'
        "from typing import Final\n\nfrom pydantic import BaseModel\n\n"
        f"{imports}\n\n"
        f"PAYLOAD_MODELS: Final[dict[tuple[str, int], type[BaseModel]]] = {{\n{entries}\n}}\n",
        encoding="utf-8",
    )
    # --isolated: the same formatting whether the output sits in the repo or in a temp dir.
    ruff = [sys.executable, "-m", "ruff"]
    pinned = ["--quiet", "--isolated", "--line-length", "100", "--target-version", "py312"]
    first_party = "lint.isort.known-first-party = ['trellis_contracts']"
    subprocess.run(
        [*ruff, "check", *pinned, "--config", first_party, "--select", "I", "--fix", str(out)],
        check=True,
    )
    subprocess.run([*ruff, "format", *pinned, str(out)], check=True)


def check() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "generated"
        generate(fresh)
        names = sorted({p.name for p in fresh.glob("*.py")} | {p.name for p in OUTPUT.glob("*.py")})
        drift = []
        for name in names:
            old, new = OUTPUT / name, fresh / name
            if not (old.exists() and new.exists() and filecmp.cmp(old, new, shallow=False)):
                drift.append(name)
                sys.stdout.writelines(
                    difflib.unified_diff(
                        old.read_text().splitlines(True) if old.exists() else [],
                        new.read_text().splitlines(True) if new.exists() else [],
                        f"committed/{name}",
                        f"regenerated/{name}",
                    )
                )
    if drift:
        print(f"\ngenerated models are stale: {', '.join(drift)}. Run the generator and commit.")
        return 1
    print(f"generated models are up to date ({len(names)} files)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if regeneration changes files")
    args = parser.parse_args()
    if args.check:
        return check()
    generate(OUTPUT)
    print(f"generated {OUTPUT.relative_to(CONTRACTS.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
