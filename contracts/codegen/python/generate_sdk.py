"""Generate the Python API client from contracts/openapi/openapi.json.

Output: contracts/packages/python/src/trellis_contracts/api/ (never edit by hand), the API half of
the published ``trellis-contracts`` package (decision T22, docs/architecture/contracts.md).

    scripts/contracts/generate.sh            # regenerate both halves
    scripts/contracts/generate.sh --check    # CI: fail if output would change

Two generated modules:

* ``models.py``: pydantic v2 models of ``components.schemas`` (datamodel-code-generator), tolerant
  readers (``extra="ignore"``), snake_case fields with camelCase aliases, no ``Any``.
* ``resources.py``: one class per OpenAPI tag (``NoticeResource``, ...) with one typed method per
  operation. Methods go through the ``HttpTransport`` protocol (hand-written, ``trellis_contracts/transport.py``), so
  the consuming application supplies retries, 429 handling, token refresh and error mapping and this
  package stays dependency-light.

The OpenAPI document is exported from the backend: ./gradlew :trellis-app:exportApiContracts.
"""

import argparse
import difflib
import filecmp
import json
import keyword
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

CONTRACTS = Path(__file__).resolve().parents[2]
OPENAPI = CONTRACTS / "openapi" / "openapi.json"
OUTPUT = CONTRACTS / "packages" / "python" / "src" / "trellis_contracts" / "api"
SOURCE = OPENAPI.relative_to(CONTRACTS.parent).as_posix()
HEADER = (
    f"# GENERATED by contracts/codegen/python/generate_sdk.py from {SOURCE}. DO NOT EDIT.\n"
    "# Change the backend, run ./gradlew :trellis-app:exportApiContracts, then: "
    "scripts/contracts/generate.sh"
)
SCHEMA_REF = "#/components/schemas/"
HTTP_METHODS = ("get", "put", "post", "delete", "patch")
CODEGEN_ARGS = [
    "--input-file-type", "openapi",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.12",
    "--snake-case-field",
    "--allow-population-by-field-name",
    "--use-annotated",
    "--field-constraints",
    "--use-standard-collections",
    "--use-union-operator",
    "--extra-fields", "ignore",
    "--output-datetime-class", "AwareDatetime",
    "--disable-timestamp",
    "--use-double-quotes",
    "--capitalise-enum-members",
    "--set-default-enum-member",
    "--use-schema-description",
    "--no-use-field-description",
    "--no-formatters",  # formatting happens once, in generate(), with pinned settings
]  # fmt: skip
PRIMITIVES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}


@dataclass(frozen=True)
class Param:
    name: str  # wire name
    py_name: str
    location: str  # path | query | header
    annotation: str
    required: bool


@dataclass
class Operation:
    method: str
    path: str
    operation_id: str
    summary: str | None
    params: list[Param]
    body_model: str | None
    response: str  # Python type of the 2xx body, "None" when empty


@dataclass
class Resource:
    tag: str
    operations: list[Operation] = field(default_factory=list)

    @property
    def class_name(self) -> str:
        return "".join(part.capitalize() for part in re.split(r"[^A-Za-z0-9]+", self.tag)) + "Resource"

    @property
    def attribute(self) -> str:
        return _snake(self.tag)


def _snake(name: str) -> str:
    text = re.sub(r"[^A-Za-z0-9]+", "_", name)
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", text).lower().strip("_")
    return f"{text}_" if keyword.iskeyword(text) else text


def _type_of(schema: dict[str, object]) -> str:
    ref = schema.get("$ref")
    if isinstance(ref, str):
        return ref.removeprefix(SCHEMA_REF)
    kind = schema.get("type")
    enum = schema.get("enum")
    if kind == "string" and isinstance(enum, list):
        return "Literal[" + ", ".join(json.dumps(v) for v in enum) + "]"
    if kind == "array":
        items = schema.get("items")
        return f"list[{_type_of(items if isinstance(items, dict) else {})}]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        value = _type_of(extra) if isinstance(extra, dict) else "JsonValue"
        return f"dict[str, {value}]"
    if isinstance(kind, str) and kind in PRIMITIVES:
        return PRIMITIVES[kind]
    return "JsonValue"


def _response_type(responses: dict[str, dict[str, object]]) -> str:
    for status in sorted(responses):
        if not status.startswith("2"):
            continue
        content = responses[status].get("content")
        if not isinstance(content, dict) or not content:
            return "None"
        media = next(iter(content.values()))
        schema = media.get("schema") if isinstance(media, dict) else None
        return _type_of(schema) if isinstance(schema, dict) else "JsonValue"
    return "None"


def _resources(document: dict[str, object]) -> list[Resource]:
    by_tag: dict[str, Resource] = {}
    paths = document["paths"]
    assert isinstance(paths, dict)
    for path in sorted(paths):
        item = paths[path]
        for method in HTTP_METHODS:
            op = item.get(method)
            if op is None:
                continue
            params = []
            for raw in op.get("parameters", []):
                py_name = _snake(raw["name"])
                annotation = _type_of(raw.get("schema", {}))
                params.append(
                    Param(raw["name"], py_name, raw["in"], annotation, bool(raw.get("required")))
                )
            body_model = None
            body = op.get("requestBody")
            if body is not None:
                schema = next(iter(body["content"].values()))["schema"]
                body_model = _type_of(schema)
            tag = (op.get("tags") or ["default"])[0]
            resource = by_tag.setdefault(tag, Resource(tag))
            resource.operations.append(
                Operation(
                    method.upper(),
                    path,
                    op["operationId"],
                    op.get("summary"),
                    params,
                    body_model,
                    _response_type(op["responses"]),
                )
            )
    return [by_tag[tag] for tag in sorted(by_tag)]


def _signature(op: Operation) -> str:
    args = ["self"]
    args += [f"{p.py_name}: {p.annotation}" for p in op.params if p.location == "path"]
    if op.body_model:
        args.append(f"body: models.{op.body_model}")
    rest = [p for p in op.params if p.location != "path"]
    if rest:
        args.append("*")
        args += [f"{p.py_name}: {p.annotation}" for p in rest if p.required]
        args += [f"{p.py_name}: {p.annotation} | None = None" for p in rest if not p.required]
    return ", ".join(args)


def _qualified(type_name: str) -> str:
    """Model names get the ``models.`` prefix; builtins, Literal and JsonValue stay as they are."""
    return re.sub(
        r"\b([A-Z][A-Za-z0-9]*)\b",
        lambda m: m.group(1) if m.group(1) in {"Literal", "JsonValue"} else f"models.{m.group(1)}",
        type_name,
    )


def _method(op: Operation, adapters: dict[str, str]) -> str:
    lines = [f"    def {_snake(op.operation_id)}({_signature(op)}) -> {_qualified(op.response)}:"]
    lines.append(f'        """``{op.method} {op.path}``{": " + op.summary if op.summary else ""}."""')
    path_expr = op.path
    for p in op.params:
        if p.location == "path":
            path_expr = path_expr.replace(
                "{" + p.name + "}", "{quote(str(" + p.py_name + '), safe="")}'
            )
    path_literal = f'f"{path_expr}"' if "{" in path_expr else f'"{path_expr}"'
    call = [f'"{op.method}"', path_literal]
    for location, var in (("query", "params"), ("header", "headers")):
        group = [p for p in op.params if p.location == location]
        if not group:
            continue
        lines.append(f"        {var}: dict[str, str] = {{}}")
        for p in group:
            value = p.py_name if p.annotation == "str" else f"str({p.py_name})"
            if p.required:
                lines.append(f'        {var}["{p.name}"] = {value}')
            else:
                lines.append(f"        if {p.py_name} is not None:")
                lines.append(f'            {var}["{p.name}"] = {value}')
        call.append(f"{var}={var}")
    if op.body_model:
        call.append('json=body.model_dump(mode="json", by_alias=True, exclude_none=True)')
    request = f"self._http.request({', '.join(call)})"
    if op.response == "None":
        lines.append(f"        {request}")
    elif op.response in adapters:
        lines.append(f"        response = {request}")
        lines.append(f"        return {adapters[op.response]}.validate_json(response.content)")
    else:
        lines.append(f"        response = {request}")
        lines.append(f"        return models.{op.response}.model_validate_json(response.content)")
    return "\n".join(lines)


def _resources_module(resources: list[Resource]) -> str:
    adapters: dict[str, str] = {}
    for resource in resources:
        for op in resource.operations:
            if op.response != "None" and not re.fullmatch(r"[A-Z][A-Za-z0-9]*", op.response):
                adapters.setdefault(op.response, f"_{_snake(op.operation_id).upper()}_RESPONSE")
    body = [
        _method(op, adapters) for resource in resources for op in resource.operations
    ] + list(adapters)
    used = "\n".join(body)
    typing_names = ["Final"] + (["Literal"] if "Literal[" in used else [])
    out = [
        HEADER,
        '"""Typed operations of the backend API, one class per OpenAPI tag."""',
        "",
        "from functools import cached_property",
        f"from typing import {', '.join(typing_names)}",
        "from urllib.parse import quote",
        "",
        "from pydantic import TypeAdapter",
        "",
        *(["from pydantic import JsonValue"] if "JsonValue" in used else []),
        "from trellis_contracts.api import models",
        "from trellis_contracts.transport import HttpTransport",
        "",
    ]
    for type_name, adapter in sorted(adapters.items(), key=lambda kv: kv[1]):
        out.append(
            f"{adapter}: Final[TypeAdapter[{_qualified(type_name)}]] = "
            f"TypeAdapter({_qualified(type_name)})"
        )
    for resource in resources:
        out += ["", "", f"class {resource.class_name}:"]
        out.append(f'    """Operations tagged ``{resource.tag}``."""')
        out += ["", "    def __init__(self, http: HttpTransport) -> None:", "        self._http = http"]
        for op in resource.operations:
            out += ["", _method(op, adapters)]
    out += [
        "",
        "",
        "class GeneratedResources:",
        '    """Mixin for ``TrellisApi``: one property per resource, sharing ``self.http``."""',
        "",
        "    http: HttpTransport",
    ]
    for resource in resources:
        out += [
            "",
            "    @cached_property",
            f"    def {resource.attribute}(self) -> {resource.class_name}:",
            f"        return {resource.class_name}(self.http)",
        ]
    return "\n".join(out) + "\n"


def _models(target: Path) -> None:
    subprocess.run(
        [
            sys.executable, "-m", "datamodel_code_generator",
            "--input", str(OPENAPI), "--output", str(target),
            "--custom-file-header", HEADER,
            *CODEGEN_ARGS,
        ],
        check=True,
    )  # fmt: skip
    text = target.read_text(encoding="utf-8")
    if re.search(r"\bAny\b", text):
        raise SystemExit("models.py would contain typing.Any: give the schema a precise type")


def generate(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for stale in out.glob("*.py"):
        stale.unlink()
    (out / "__init__.py").write_text(
        f'{HEADER}\n"""Client code generated from the OpenAPI contract."""\n', encoding="utf-8"
    )
    _models(out / "models.py")
    document = json.loads(OPENAPI.read_text(encoding="utf-8"))
    (out / "resources.py").write_text(_resources_module(_resources(document)), encoding="utf-8")
    ruff = [sys.executable, "-m", "ruff"]
    pinned = ["--quiet", "--isolated", "--line-length", "100", "--target-version", "py312"]
    first_party = "lint.isort.known-first-party = ['trellis_contracts']"
    subprocess.run(
        [*ruff, "check", *pinned, "--config", first_party, "--select", "I", "--fix", str(out)],
        check=True,
    )
    subprocess.run([*ruff, "format", *pinned, str(out)], check=True)


def check() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "generated"
        generate(fresh)
        names = sorted({p.name for p in fresh.glob("*.py")} | {p.name for p in OUTPUT.glob("*.py")})
        drift = []
        for name in names:
            old, new = OUTPUT / name, fresh / name
            if not (old.exists() and new.exists() and filecmp.cmp(old, new, shallow=False)):
                drift.append(name)
                sys.stdout.writelines(
                    difflib.unified_diff(
                        old.read_text().splitlines(True) if old.exists() else [],
                        new.read_text().splitlines(True) if new.exists() else [],
                        f"committed/{name}",
                        f"regenerated/{name}",
                    )
                )
    if drift:
        print(f"\ngenerated SDK is stale: {', '.join(drift)}. Run the generator and commit.")
        return 1
    print(f"generated SDK is up to date ({len(names)} files)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if regeneration changes files")
    args = parser.parse_args()
    if args.check:
        return check()
    generate(OUTPUT)
    print(f"generated {OUTPUT.relative_to(CONTRACTS.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
